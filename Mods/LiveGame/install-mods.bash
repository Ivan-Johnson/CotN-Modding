#!/usr/bin/env bash
# Installs the named mods from Mods/ into the game as a single bundle mod.
#
# The game only auto-loads mods it already has enabled, so installing each mod
# separately would need a manual enable per mod. A bundle is one mod, enabled
# once by hand, whose subfolders are the mods being installed. Installing a
# different set replaces the bundle's contents, which uninstalls the rest.
#
# A module's name is "<mod name>.<path>", so inside the bundle every mod's
# modules gain the bundle's name as a prefix. bundle-layout.lua, which also
# does the rewriting, defines the form a mod must name modules in for that.
#
# Internal to live-game-run, which takes the game-instance lock around it
# (ADR 0009); nothing else calls it.
#
# Usage: install-mods [MOD...]
#
# Environment:
#   ITJ_MODS_ROOT               override; default <git toplevel>/Mods
#   COTN_LOCAL_MODS_DIR         the game's local mods directory
#   ITJ_BUNDLE_NAME             bundle mod name (default: DevBundle)
#   ITJ_BUNDLE_RELOAD_TRIGGER   optional "<mod>/<file>.lua" in the bundle to
#                               prefix line 1 of with a print of the reload
#                               token; the changed file forces a reload, and
#                               the printed line shows the new copy loaded.
#                               Prefixing line 1 keeps every line number.
#   ITJ_BUNDLE_RELOAD_TOKEN     the token the trigger prints, as
#                               "[install-mods] loaded <token>" (default: the
#                               time in nanoseconds)
#   ITJ_BUNDLE_STAMP_ALL        "1" to prefix line 1 of every installed Lua
#                               file, the trigger too, with a print of
#                               "[install-mods] loaded <token> <mod>/<path>",
#                               so the log shows which files ran this copy.
#                               Every file then changes on each install, so
#                               the game reloads all of them each time.
#   ITJ_BUNDLE_EXTRA_FILE       optional "<mod>/<file>" in the bundle to create
#                               holding ITJ_BUNDLE_EXTRA_CONTENT, so the mod
#                               sees it from its first load; a reinstall
#                               without it removes the file
set -euo pipefail

modsRoot="${ITJ_MODS_ROOT:-$(git rev-parse --show-toplevel)/Mods}"
bundleName="${ITJ_BUNDLE_NAME:-DevBundle}"

mods=("$@")

for mod in "${mods[@]}"; do
	if [[ ! $mod =~ ^[A-Za-z0-9_]+$ || ! -f "$modsRoot/$mod/mod.json" ]]; then
		echo "install-mods: '$mod' is not a mod under $modsRoot" >&2
		exit 1
	fi
done

bundle-layout check-install "$modsRoot" "${mods[@]}"

# The bundle declares the synchronyVersion its mods share; check-install has
# just made them agree. With nothing to install, every mod under $modsRoot
# stands in, and the mods-layout check keeps those in agreement.
if ((${#mods[@]} > 0)); then
	versionManifests=("$modsRoot/${mods[0]}/mod.json")
else
	versionManifests=("$modsRoot"/*/mod.json)
fi
synchronyVersion="$(jq -rn 'first(inputs.synchronyVersion)' "${versionManifests[@]}")"

stage="$(mktemp -d)"
trap 'rm -rf "$stage"' EXIT

for mod in "${mods[@]}"; do
	rsync -rlt "$modsRoot/$mod/" "$stage/$mod/"
done

jq -n \
	--arg name "$bundleName" \
	--arg synchronyVersion "$synchronyVersion" \
	'{
		namespace: $name,
		displayName: $name,
		version: "0.0.0",
		synchronyVersion: $synchronyVersion,
		description: "Generated by install-mods; holds the mods being developed. Not intended for players.",
		author: "install-mods",
		dependencies: {},
		api: {scriptPath: ""},
		tags: [],
		name: $name
	}' >"$stage/mod.json"

bundle-layout rewrite "$stage" "$bundleName" "${mods[@]}"

if [[ -n ${ITJ_BUNDLE_RELOAD_TRIGGER:-} ]]; then
	# A new file reloads nothing, so a misspelled trigger would wait in vain.
	if [[ ! -f "$stage/$ITJ_BUNDLE_RELOAD_TRIGGER" ]]; then
		echo "install-mods: the reload trigger $ITJ_BUNDLE_RELOAD_TRIGGER is not a file of the installed mods" >&2
		exit 1
	fi
	if [[ $ITJ_BUNDLE_RELOAD_TRIGGER != *.lua ]]; then
		echo "install-mods: the reload trigger $ITJ_BUNDLE_RELOAD_TRIGGER is not a Lua file, so it cannot print the reload token" >&2
		exit 1
	fi
fi

# stamp FILE TEXT: prefixes line 1 of FILE with a print of
# "[install-mods] loaded TEXT"; prefixing line 1 keeps every line number.
stamp() {
	{
		printf 'print("[install-mods] loaded %s"); ' "$2"
		cat "$1"
	} >"$1.new"
	mv "$1.new" "$1"
}

token="${ITJ_BUNDLE_RELOAD_TOKEN:-$(date +%s%N)}"
if [[ ${ITJ_BUNDLE_STAMP_ALL:-} == 1 ]]; then
	shopt -s globstar nullglob
	for file in "$stage"/*/**/*.lua; do
		stamp "$file" "$token ${file#"$stage"/}"
	done
elif [[ -n ${ITJ_BUNDLE_RELOAD_TRIGGER:-} ]]; then
	stamp "$stage/$ITJ_BUNDLE_RELOAD_TRIGGER" "$token"
fi

if [[ -n ${ITJ_BUNDLE_EXTRA_FILE:-} ]]; then
	echo "${ITJ_BUNDLE_EXTRA_CONTENT:-}" >"$stage/$ITJ_BUNDLE_EXTRA_FILE"
fi

rsync -rlt --delete --delay-updates "$stage/" "$COTN_LOCAL_MODS_DIR/$bundleName/"
echo "install-mods: installed ${mods[*]:-nothing} into $bundleName"
