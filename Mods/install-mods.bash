#!/usr/bin/env bash
# Installs the named mods from Mods/ into the game as a single bundle mod.
#
# The game only auto-loads mods it already has enabled, so installing each mod
# separately would need a manual enable per mod. A bundle is one mod, enabled
# once by hand, whose subfolders are the mods being installed. Installing a
# different set replaces the bundle's contents, which uninstalls the rest.
#
# A module's name is "<mod name>.<path>", so inside the bundle every mod's
# modules gain the bundle's name as a prefix. bundle-layout.lua, which also
# does the rewriting, defines the form a mod must name modules in for that.
#
# Usage: install-mods [MOD...]
#
# Environment:
#   ITJ_FLAKE_ROOT              repo root
#   COTN_LOCAL_MODS_DIR         the game's local mods directory
#   ITJ_BUNDLE_NAME             bundle mod name (default: DevBundle)
#   ITJ_BUNDLE_RELOAD_TRIGGER   optional "<mod>/<file>" in the bundle to
#                               append a timestamp comment to, forcing a reload
#   ITJ_BUNDLE_EXTRA_FILE       optional "<mod>/<file>" in the bundle to create
#                               holding ITJ_BUNDLE_EXTRA_CONTENT, so the mod
#                               sees it from its first load; a reinstall
#                               without it removes the file
set -euo pipefail

modsRoot="$ITJ_FLAKE_ROOT/Mods"
bundleName="${ITJ_BUNDLE_NAME:-DevBundle}"
synchronyVersion="4.2.1"

mods=("$@")

for mod in "${mods[@]}"; do
	if [[ ! $mod =~ ^[A-Za-z0-9_]+$ || ! -f "$modsRoot/$mod/mod.json" ]]; then
		echo "install-mods: '$mod' is not a mod under $modsRoot" >&2
		exit 1
	fi
done

bundle-layout check-install "$modsRoot" "${mods[@]}"

stage="$(mktemp -d)"
trap 'rm -rf "$stage"' EXIT

for mod in "${mods[@]}"; do
	rsync -rlt "$modsRoot/$mod/" "$stage/$mod/"
done

jq -n \
	--arg name "$bundleName" \
	--arg synchronyVersion "$synchronyVersion" \
	'{
		namespace: $name,
		displayName: $name,
		version: "0.0.0",
		synchronyVersion: $synchronyVersion,
		description: "Generated by install-mods; holds the mods being developed. Not intended for players.",
		author: "install-mods",
		dependencies: {},
		api: {scriptPath: ""},
		tags: [],
		name: $name
	}' >"$stage/mod.json"

bundle-layout rewrite "$stage" "$bundleName" "${mods[@]}"

if [[ -n ${ITJ_BUNDLE_RELOAD_TRIGGER:-} ]]; then
	echo "-- install-mods trigger $(date +%s%N)" >>"$stage/$ITJ_BUNDLE_RELOAD_TRIGGER"
fi

if [[ -n ${ITJ_BUNDLE_EXTRA_FILE:-} ]]; then
	echo "${ITJ_BUNDLE_EXTRA_CONTENT:-}" >"$stage/$ITJ_BUNDLE_EXTRA_FILE"
fi

rsync -rlt --delete --delay-updates "$stage/" "$COTN_LOCAL_MODS_DIR/$bundleName/"
echo "install-mods: installed ${mods[*]:-nothing} into $bundleName"
